import assert from 'node:assert/strict';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { openCloudStorage } from '../../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../../onecrew_lite-app/src/cloud/shop-data.ts';
import { parseApplicationJson, stringifyApplicationJson } from '../../onecrew_lite-contracts/src/json.ts';
import { campaignResults, reviewMaterial } from '../../onecrew_lite-web/src/cloud/result-contracts.ts';

// 只复核原执行器已经从真实网页保存的数据，不追加平台或模型请求。
const directory = resolve(process.argv[2]);
await using ownership = new AsyncDisposableStack();
const storage = await openCloudStorage(directory);
ownership.defer(() => storage.close());
const runtimes = new ShopRuntimeRegistry();
ownership.defer(() => runtimes.close());
const metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
metadata.close();
assert.equal(shops.length, 1);
const shop = shops[0].shop, campaign = 'cloud-live-search';
const data = new ShopDataService(storage.lease, storage.installations, runtimes);
const results = await data.results(shop, campaign, null, null);
const decoded = campaignResults.parse(parseApplicationJson(stringifyApplicationJson({ ...results, library: { table: null, creators: null } })));
assert.equal(decoded.hits.length, 2);
assert.equal(decoded.candidates.length, 1);
const candidate = decoded.candidates[0], hit = decoded.hits.find(hit => candidate.evidence.source_urls.includes(hit.source_url));
assert.ok(hit);
const material = await data.reviewMaterial(shop, campaign, hit.id, decoded.campaign.revision);
const saved = reviewMaterial.parse(parseApplicationJson(stringifyApplicationJson({ material }))).material;
assert.equal(saved.video_description, candidate.evidence.video_description);
assert.equal(saved.hit.source_url, hit.source_url);
assert.equal((await data.campaign(shop, campaign)).used_calls, 2);
console.info(JSON.stringify({ event: 'cloud.saved_results_and_material_verified', searchHits: decoded.hits.length, candidates: decoded.candidates.length, savedDescriptionBytes: Buffer.byteLength(saved.video_description), noAdditionalPlatformReads: true, browserContractDecoded: true }));
