import assert from 'node:assert/strict';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { openCloudStorage } from '../../../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../../../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../../../onecrew_lite-app/src/cloud/shop-data.ts';
import { ShopBrowserManager } from '../../../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { CloudDiscoveryReader } from '../../../onecrew_lite-app/src/cloud/discovery-reader.ts';

const directory = resolve(process.argv[2]);
const metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
metadata.close();
assert.equal(shops.length, 1);
await using resources = new AsyncDisposableStack();
const storage = await openCloudStorage(directory);
resources.defer(() => storage.close());
const browsers = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
resources.defer(() => browsers.close());
const runtimes = new ShopRuntimeRegistry();
resources.defer(() => runtimes.close());
const data = await new ShopDataService(storage.lease, storage.installations, runtimes).resolve(shops[0].shop);
const reader = new CloudDiscoveryReader({ data, workspace: storage.installations.workspace(shops[0].shop), browsers });
const binding = reader.binding(data.runtime.context, 'cloud');
const cancellation = new AbortController(), reason = new Error('local_read_cancelled');
const timer = setTimeout(() => cancellation.abort(reason), 1000);
resources.defer(() => clearTimeout(timer));
await assert.rejects(reader.youtubeSearch(binding.withSignal(cancellation.signal), 'water bottle reviews', 2), error => error === reason);
await reader.checkBrowserProfile(binding);
assert.equal(browsers.busy(shops[0].shop), false);
console.info(JSON.stringify({ event: 'cloud.actual_read_cancelled', cancellationReasonPreserved: true, subsequentConnectionSucceeded: true, modelCalled: false }));
