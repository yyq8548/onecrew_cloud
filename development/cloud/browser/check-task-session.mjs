import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { openCloudStorage } from '../../../onecrew_lite-app/src/cloud/storage.ts';
import { ShopBrowserManager } from '../../../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { dockerCommand } from '../../../onecrew_lite-app/src/cloud/docker-browser-client.ts';

const directory = resolve(process.argv[2]);
const metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
metadata.close();
assert.equal(shops.length, 1);
await using resources = new AsyncDisposableStack();
const storage = await openCloudStorage(directory); resources.defer(() => storage.close());
const browsers = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
resources.defer(() => browsers.close());
const workspace = storage.installations.workspace(shops[0].shop), signal = new AbortController().signal;
const scope = createHash('sha256').update(directory).digest('hex').slice(0, 16);
const running = async () => (await dockerCommand(['ps', '--filter', `label=onecrew.scope=${scope}`, '--format', '{{.ID}}'])).stdout.trim();
const ready = Promise.withResolvers(), release = Promise.withResolvers();
const before = storage.installations.browserSnapshot(workspace.shop);
const task = browsers.task(workspace, signal, async stopped => {
  await browsers.read(workspace, { method: 'checkBrowserProfile', args: [] }, stopped);
  const container = await running(); assert.ok(container);
  const auth = await browsers.read(workspace, { method: 'checkCreatorAuthStatus', args: ['instagram'] }, stopped);
  assert.equal(await running(), container);
  assert.equal(storage.installations.browserSnapshot(workspace.shop), before);
  ready.resolve(auth); await release.promise;
  return auth;
});
task.catch(error => ready.reject(error));
const auth = await ready.promise;
assert.equal(browsers.busy(workspace.shop), true);
await assert.rejects(browsers.read(workspace, { method: 'checkBrowserProfile', args: [] }, signal), /worker_busy/);
await assert.rejects(browsers.disconnect(workspace, 'instagram', signal), /worker_busy/);
release.resolve(); await task;
assert.notEqual(storage.installations.browserSnapshot(workspace.shop), before);
assert.equal(await running(), '');
assert.equal(browsers.busy(workspace.shop), false);

const waiting = Promise.withResolvers();
const interrupted = browsers.task(workspace, signal, async stopped => {
  await browsers.read(workspace, { method: 'checkBrowserProfile', args: [] }, stopped);
  const aborted = new Promise(resolve => stopped.addEventListener('abort', resolve, { once: true }));
  waiting.resolve(); await aborted; stopped.throwIfAborted();
});
interrupted.catch(error => waiting.reject(error));
await waiting.promise;
const rejected = assert.rejects(interrupted, /cloud.shop_stopping/);
browsers.suspend(workspace.shop); await rejected;
assert.equal(await running(), '');
assert.equal(browsers.busy(workspace.shop), false);
const restored = await browsers.read(workspace, { method: 'checkCreatorAuthStatus', args: ['instagram'] }, signal);
const { checked_at: checkedAt, ...identity } = auth;
const { checked_at: restoredAt, ...restoredIdentity } = restored;
assert.deepEqual(restoredIdentity, identity);
assert.ok(restoredAt >= checkedAt);
console.info(JSON.stringify({ event: 'cloud.task_session_verified', consecutiveReadsSameContainer: true, snapshotUnchangedDuringTask: true, snapshotSavedAtEnd: true, externalReadAndDisconnectRejected: true, cancellationBetweenReadsDrained: true, authStatePreservedAfterReopen: true, modelCalled: false }));
