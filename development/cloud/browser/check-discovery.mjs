import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { openCloudStorage } from '../../../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../../../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../../../onecrew_lite-app/src/cloud/shop-data.ts';
import { ShopBrowserManager } from '../../../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { createCloudDiscoveryDependencies } from '../../../onecrew_lite-app/src/cloud/discovery-dependencies.ts';
import { ServerSemanticClient } from '../../../onecrew_lite-app/src/discovery/server-semantic-client.ts';
import { DiscoverySearchExecutor } from '../../../onecrew_lite-app/src/discovery/search-execution.ts';
import { DiscoveryVideoExecutor } from '../../../onecrew_lite-app/src/discovery/video-execution.ts';
import { OpenCliError } from '../../../onecrew_lite-app/src/platforms/opencli/errors.ts';
import { parseApplicationJson, stringifyApplicationJson } from '../../../onecrew_lite-contracts/src/json.ts';
import { campaignResults, reviewMaterial } from '../../../onecrew_lite-web/src/cloud/result-contracts.ts';

const { Session } = createRequire(new URL('../../../onecrew_lite-app/package.json', import.meta.url))('@shopify/shopify-api');
const directory = resolve(process.argv[2]);
await using ownership = new AsyncDisposableStack();
const storage = await openCloudStorage(directory, true);
ownership.defer(() => storage.close());
const manager = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
ownership.defer(() => manager.close());
const runtimes = new ShopRuntimeRegistry();
ownership.defer(() => runtimes.close());
const shop = `discovery-${randomBytes(4).toString('hex')}.myshopify.com`;
// Session 仅作为本地存储归属输入；本脚本不调用 Shopify 或模型，不声明对应验收通过。
const workspace = storage.installations.install(new Session({ id: `offline_${shop}`, shop, state: '', isOnline: false, scope: 'read_products', accessToken: randomBytes(32).toString('hex') }), 0);
const storeData = new ShopDataService(storage.lease, storage.installations, runtimes);
const data = await storeData.resolve(shop);
const model = new ServerSemanticClient({ endpoint: 'http://127.0.0.1:8789/v1/chat/completions', model: 'onecrew-qwen3-4b-q4', revision: 'Qwen-bc640142-Q4_K_M:7485fe6f:llama-8c74db29', timeoutMs: 600000, maximumOutputTokens: 4096, maximumResponseBytes: 1024 * 1024 });
const dependencies = createCloudDiscoveryDependencies(data, workspace, manager, model);
ownership.defer(() => dependencies.stopSemantic());
const timeout = AbortSignal.timeout(360000);
const stop = () => runtimes.suspend(shop);
timeout.addEventListener('abort', stop, { once: true });
ownership.defer(() => timeout.removeEventListener('abort', stop));
const context = data.runtime.context;
const { reader, browsers } = await dependencies.reads(context);
const binding = await browsers.resolve(context, 'cloud');
const [capabilities] = await Promise.all([reader.creatorSearchCapabilities(), reader.checkBrowserProfile(binding)]);
assert.deepEqual(capabilities.map(source => source.platform).sort(), ['instagram', 'tiktok', 'twitter', 'youtube']);
await reader.checkYoutubeEvidenceProfile(binding);
const diagnostics = [];
await assert.rejects(reader.withDiagnostics(error => diagnostics.push(error)).youtubeChannel(binding, 'invalid-channel'), error => error instanceof OpenCliError && error.code === 'opencli_invalid_input');
assert.equal(diagnostics.length, 1);
assert.equal(diagnostics[0].code, 'opencli_invalid_input');
const repositories = data.databases.discoveryResolver();
const owned = await repositories.resolve(context);
const repository = owned.repository;
const campaign = 'cloud-live-search';
// 这是明确的手工任务输入；候选和证据全部由原执行器读取真实网页后写入。
repository.create({ id: campaign, brief: '寻找护肤创作者', opencli_version: '1.8.8', criteria: {}, scopes: [{ platform: 'youtube', profile_ref: 'cloud', keywords: ['skincare'] }], target_count: 2 });
repository.approve(campaign, 1);
const searched = await new DiscoverySearchExecutor(data.runtime.accounts, repositories, browsers, reader).searchOnce(context, { planId: campaign, revision: 1, platform: 'youtube', profileRef: 'cloud', limit: 2 });
assert.equal(searched.returned_hits, 2);
const hit = repository.nextVideoHit(campaign);
assert.ok(hit);
await new DiscoveryVideoExecutor(data.runtime.accounts, repositories, browsers, reader).readOnce(context, { campaign_id: campaign, expected_revision: 1, profile_ref: hit.profile_ref, search_hit_id: hit.id });
const candidates = repository.listCandidates({ campaign_id: campaign, after_id: null, limit: 10 });
assert.equal(candidates.length, 1);
const candidate = candidates[0];
assert.equal(candidate.platform, 'youtube');
assert.ok(candidate.platform_account_id.startsWith('UC'));
assert.equal(typeof candidate.evidence.video_description, 'string');
assert.ok(candidate.evidence.video_description.length > 0);
const current = repository.getPlan(campaign);
assert.equal(current.used_calls, 2);
const results = await storeData.results(shop, campaign, null, null);
const decodedResults = campaignResults.parse(parseApplicationJson(stringifyApplicationJson({ ...results, library: { table: null, creators: null } })));
assert.equal(decodedResults.hits.length, 2);
assert.equal(decodedResults.candidates.length, 1);
const material = await storeData.reviewMaterial(shop, campaign, hit.id, 1);
const decodedMaterial = reviewMaterial.parse(parseApplicationJson(stringifyApplicationJson({ material }))).material;
assert.equal(decodedMaterial.video_description, candidate.evidence.video_description);
const savedHit = results.hits.find(saved => saved.id === hit.id);
assert.ok(savedHit);
assert.equal(decodedMaterial.hit.source_url, savedHit.source_url);
assert.equal(repository.getPlan(campaign).used_calls, 2);
console.info(JSON.stringify({ event: 'cloud.saved_results_and_material_verified', searchHits: decodedResults.hits.length, candidates: decodedResults.candidates.length, savedDescriptionBytes: Buffer.byteLength(decodedMaterial.video_description), noAdditionalPlatformReads: true, browserContractDecoded: true }));
console.info(JSON.stringify({ event: 'cloud.original_discovery_executors_verified', shop, campaignId: campaign, searchHits: searched.returned_hits, sourceUrls: candidate.evidence.source_urls, descriptionBytes: Buffer.byteLength(candidate.evidence.video_description), recordedCalls: current.used_calls, typedFailure: diagnostics[0].code }));
