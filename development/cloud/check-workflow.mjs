import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { setTimeout } from 'node:timers/promises';
import { openCloudStorage } from '../../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../../onecrew_lite-app/src/cloud/shop-data.ts';
import { openCloudLibrary, ShopLibraryService } from '../../onecrew_lite-app/src/cloud/shop-library.ts';
import { ShopBrowserManager } from '../../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { CloudCampaignService } from '../../onecrew_lite-app/src/cloud/campaign-service.ts';
import { shopifyProductSnapshot } from '../../onecrew_lite-app/src/cloud/campaign-jobs.ts';
import { parseApplicationJson, stringifyApplicationJson } from '../../onecrew_lite-contracts/src/json.ts';
import { campaignResults } from '../../onecrew_lite-web/src/cloud/result-contracts.ts';
import { createCheckModel } from './model/check-client.mjs';

const require = createRequire(new URL('../../onecrew_lite-app/package.json', import.meta.url));
const { load } = require('cheerio');
const [dataDirectory, productFile, productUrl, platform = 'youtube', minimum = '10000', maximum = '1000000', resumeCampaign] = process.argv.slice(2);
assert.ok(dataDirectory && productFile && productUrl, '用法：node development/cloud/check-workflow.mjs <独立本地数据目录> <真实公开商品JSON> <商品页面URL> [平台] [最少粉丝] [最多粉丝]');
const directory = resolve(dataDirectory), origin = 'https://cloud.example.com';
const captured = await readFile(resolve(productFile), 'utf8');
const source = parseApplicationJson(captured).product;
// 使用真实商店公开 JSON；本地既有安装记录只决定存储归属，不代表 Shopify 安装或成员验收。
const product = shopifyProductSnapshot.parse({ id: `gid://shopify/Product/${source.id}`, title: source.title, description: load(source.body_html).text(), onlineStoreUrl: productUrl, updatedAt: new Date(source.updated_at).toISOString(), captured_at: Date.now() });
const metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
metadata.close();
assert.equal(shops.length, 1, '必须使用只有一个本地验证归属的独立数据副本');
const shop = shops[0].shop;
const id = resumeCampaign ?? randomUUID(), input = { id, product_id: product.id, platforms: [platform], min_followers: Number(minimum), max_followers: Number(maximum) };
let jobId = id;
const evidenceFile = join(directory, `workflow-${id}.json`);
await using ownership = new AsyncDisposableStack();
const storage = await openCloudStorage(directory);
ownership.defer(() => storage.close());
storage.campaignJobs.recover();
const browsers = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
ownership.defer(() => browsers.close());
const tables = await openCloudLibrary(storage.lease, origin);
ownership.defer(() => tables.close());
const runtimes = new ShopRuntimeRegistry();
ownership.defer(() => runtimes.close());
const data = new ShopDataService(storage.lease, storage.installations, runtimes);
const library = new ShopLibraryService(tables, data, origin), failures = [], fatal = [];
const service = new CloudCampaignService({ data, installations: storage.installations, jobs: storage.campaignJobs, templates: storage.campaignTemplates, browsers, library, model: createCheckModel(), reportFailure: failure => { failures.push(failure); console.error(JSON.stringify({ event: 'cloud.workflow_failure', ...failure })); }, onFatal: error => { fatal.push(error); console.error(error); } });
const loadProduct = async productId => { assert.equal(productId, product.id); return product; };
console.info(JSON.stringify({ event: 'cloud.workflow_started', id, product: { id: product.id, title: product.title, source: productUrl }, input, evidenceFile, shopifyNetworkVerified: false }));
if (resumeCampaign) {
  const plan = await data.campaign(shop, id);
  const job = await service.start(shop, id, { id: randomUUID(), expected_revision: plan.revision });
  jobId = job.id;
} else await service.create(shop, input, loadProduct);
const stop = () => { void service.cancelDraft(shop, jobId).then(() => undefined, error => { fatal.push(error); console.error(error); }); };
process.once('SIGINT', stop);
ownership.defer(() => process.removeListener('SIGINT', stop));
let previous = '', status;
const deadline = Date.now() + 20 * 60 * 1000;
while (true) {
  status = await service.status(shop, jobId);
  const progress = stringifyApplicationJson({ state: status.job.state, phase: status.job.phase, counts: status.counts, execution: status.execution });
  if (progress !== previous) { console.info(progress); previous = progress; }
  if (status.job.state !== 'running') break;
  if (Date.now() > deadline) { await service.cancelDraft(shop, jobId); throw new Error('cloud.workflow_deadline_exceeded'); }
  await setTimeout(5000);
}
await writeFile(evidenceFile, stringifyApplicationJson({ product, status, failures, shopifyNetworkVerified: false }), { flag: 'wx', mode: 0o600 });
assert.equal(status.job.state, 'completed', stringifyApplicationJson(status));
const result = campaignResults.parse(parseApplicationJson(stringifyApplicationJson({ ...await data.results(shop, id, null, null), library: await library.campaignResults(shop, id) })));
await writeFile(evidenceFile, stringifyApplicationJson({ product, status, result, failures, shopifyNetworkVerified: false }), { mode: 0o600 });
assert.equal(status.execution?.failure_code, null);
assert.ok(['finished', 'needs_evidence'].includes(status.execution.stage));
assert.equal(result.campaign.target_count, 10);
assert.ok(result.hits.length > 0);
assert.ok(result.candidates.some(candidate => candidate.evidence.assessment?.quality_rating), '必须实际完成评分');
assert.ok(result.library.table);
assert.ok(result.library.creators.recommendations.some(creator => creator.values.score), '评分必须发布到 Library');
assert.deepEqual(failures, []);
assert.deepEqual(fatal, []);
const template = await service.saveTemplate(shop, { id: randomUUID(), name: `本地完整流程 ${product.title}`, campaign_id: id, expected_revision: result.campaign.revision });
assert.equal((await service.template(shop, template.id)).conditions.target_count, 10);
assert.equal((await service.create(shop, input, () => assert.fail('重复请求不能再次读取商品'))).id, id);
const counts = result.counts, tableId = result.library.table.id;
await ownership.disposeAsync();
await using persisted = new AsyncDisposableStack();
const reopened = await openCloudStorage(directory);
persisted.defer(() => reopened.close());
const reopenedRuntimes = new ShopRuntimeRegistry();
const reopenedTables = await openCloudLibrary(reopened.lease, origin);
persisted.defer(() => reopenedTables.close());
persisted.defer(() => reopenedRuntimes.close());
const reopenedData = new ShopDataService(reopened.lease, reopened.installations, reopenedRuntimes);
assert.deepEqual((await reopenedData.results(shop, id, null, null)).counts, counts);
assert.equal(reopened.campaignJobs.get(shop, jobId).state, 'completed');
assert.ok(reopened.campaignTemplates.get(shop, template.id));
const reopenedLibrary = new ShopLibraryService(reopenedTables, reopenedData, origin);
assert.equal((await reopenedLibrary.campaignResults(shop, id)).table.id, tableId);
console.info(stringifyApplicationJson({ event: 'cloud.workflow_verified', id, counts, tableId, templateId: template.id, evidenceFile, persistedAfterReopen: true, realSearchAndModel: true, shopifyNetworkVerified: false }));
