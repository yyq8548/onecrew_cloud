import assert from 'node:assert/strict';
import { join, resolve } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { openCloudStorage } from '../../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../../onecrew_lite-app/src/cloud/shop-data.ts';
import { openCloudLibrary, ShopLibraryService } from '../../onecrew_lite-app/src/cloud/shop-library.ts';
import { ShopBrowserManager } from '../../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { CloudCampaignService } from '../../onecrew_lite-app/src/cloud/campaign-service.ts';
import { createCheckModel } from './model/check-client.mjs';

const [dataDirectory, campaign, candidate] = process.argv.slice(2);
assert.ok(dataDirectory && campaign && candidate, '需要既有真实数据目录、任务和合格候选编号');
const directory = resolve(dataDirectory), origin = 'https://cloud.example.com';
using metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
assert.equal(shops.length, 1);
const shop = shops[0].shop;
await using ownership = new AsyncDisposableStack();
const storage = await openCloudStorage(directory); ownership.defer(() => storage.close());
const browsers = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
ownership.defer(() => browsers.close());
const tables = await openCloudLibrary(storage.lease, origin); ownership.defer(() => tables.close());
const runtimes = new ShopRuntimeRegistry(); ownership.defer(() => runtimes.close());
const data = new ShopDataService(storage.lease, storage.installations, runtimes), library = new ShopLibraryService(tables, data, origin);
const failures = [];
const service = new CloudCampaignService({ data, installations: storage.installations, jobs: storage.campaignJobs, templates: storage.campaignTemplates, browsers, library, model: createCheckModel(), reportFailure: failure => failures.push(failure), onFatal: error => failures.push(error) });
const scope = await data.resolve(shop), context = scope.runtime.context;
const owned = await scope.databases.discoveryResolver().resolve(context), plan = owned.repository.getPlan(campaign);
assert.ok(owned.repository.candidateIsQualified(campaign, candidate));
assert.ok(owned.repository.nextPublicPage(campaign, [], false, candidate), '需要有尚未读取的真实联系方式来源');
const before = await data.results(shop, campaign, null, null), started = performance.now();
const receipt = await service.findContacts(shop, campaign, candidate, plan.revision);
assert.ok(receipt.pages_read > 0 && receipt.pages_read <= 2);
assert.equal(browsers.busy(shop), false);
const after = await data.results(shop, campaign, null, null);
assert.deepEqual(after.candidates.filter(row => row.id !== candidate), before.candidates.filter(row => row.id !== candidate));
assert.deepEqual(after.candidates.map(row => [row.id, row.verdict]), before.candidates.map(row => [row.id, row.verdict]));
const savedLibrary = await library.campaignResults(shop, campaign);
assert.ok(savedLibrary.table);
assert.deepEqual(failures, []);
console.info(JSON.stringify({ event: 'cloud.selected_contacts_verified', campaign, candidate, elapsedMs: Math.round(performance.now() - started), ...receipt, otherCandidatesUnchanged: true, verdictsUnchanged: true, libraryPublished: true, emailSent: false }));
