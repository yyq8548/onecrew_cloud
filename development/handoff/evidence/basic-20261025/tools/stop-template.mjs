import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { resolve, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { setTimeout } from 'node:timers/promises';
import { openCloudStorage } from '../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../onecrew_lite-app/src/cloud/shop-data.ts';
import { openCloudLibrary, ShopLibraryService } from '../onecrew_lite-app/src/cloud/shop-library.ts';
import { ShopBrowserManager } from '../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { CloudCampaignService } from '../onecrew_lite-app/src/cloud/campaign-service.ts';
import { createCheckModel } from '../development/cloud/model/check-client.mjs';
const directory = resolve('.scratch/basic-workflow-20261025'), campaign = 'cca38d34-30b3-49f9-8639-ef5d26d38e3a', origin = 'https://cloud.example.com';
const metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
metadata.close();
assert.equal(shops.length, 1);
const shop = shops[0].shop;
await assert.rejects(fetch('http://127.0.0.1:8789/health'), error => error.cause?.code === 'ECONNREFUSED');
await using resources = new AsyncDisposableStack();
const storage = await openCloudStorage(directory);
resources.defer(() => storage.close());
const browsers = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
resources.defer(() => browsers.close());
const tables = await openCloudLibrary(storage.lease, origin);
resources.defer(() => tables.close());
const runtimes = new ShopRuntimeRegistry();
resources.defer(() => runtimes.close());
const data = new ShopDataService(storage.lease, storage.installations, runtimes), failures = [], fatal = [];
const service = new CloudCampaignService({ data, installations: storage.installations, jobs: storage.campaignJobs, templates: storage.campaignTemplates, browsers, library: new ShopLibraryService(tables, data, origin), model: createCheckModel(), reportFailure: error => failures.push(error), onFatal: error => fatal.push(error) });
const started = await service.start(shop, campaign, { id: randomUUID(), expected_revision: 1 });
await setTimeout(1000);
await service.cancelDraft(shop, started.id);
let status;
const deadline = AbortSignal.timeout(120000);
do { await setTimeout(250, undefined, { signal: deadline }); status = await service.status(shop, started.id); } while (status.job.state === 'running');
assert.equal(status.job.state, 'completed');
assert.equal(status.execution.stage, 'paused');
assert.equal(status.execution.failure_code, null);
assert.ok(status.counts.qualified >= 2);
assert.equal(browsers.busy(shop), false);
const template = storage.campaignTemplates.list(shop)[0];
const product = storage.campaignJobs.product(shop, campaign), input = { id: randomUUID(), product_id: product.id };
const generated = await service.createFromTemplate(shop, template.id, input, async id => { assert.equal(id, product.id); return product; });
await service.cancelDraft(shop, generated.id);
do { await setTimeout(250, undefined, { signal: deadline }); status = await service.status(shop, generated.id); } while (status.job.state === 'running');
assert.equal(status.job.state, 'interrupted');
assert.equal(status.job.error_code, 'cloud.job_cancelled');
assert.deepEqual(failures, []);
assert.deepEqual(fatal, []);
console.info(JSON.stringify({ event: 'cloud.basic_stop_and_template_verified', runningCampaignStopped: true, existingScoresPreserved: true, templateCreatedRealJob: true, templateJobCancelled: true, noBusyAfterDrain: true, modelServiceStopped: true, fullTaskCompleted: false }));
