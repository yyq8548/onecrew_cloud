import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { resolve, join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { openCloudStorage } from '../onecrew_lite-app/src/cloud/storage.ts';
import { ShopRuntimeRegistry } from '../onecrew_lite-app/src/cloud/shop-runtime-registry.ts';
import { ShopDataService } from '../onecrew_lite-app/src/cloud/shop-data.ts';
import { openCloudLibrary, ShopLibraryService } from '../onecrew_lite-app/src/cloud/shop-library.ts';
import { ShopBrowserManager } from '../onecrew_lite-app/src/cloud/shop-browser-manager.ts';
import { CloudCampaignService } from '../onecrew_lite-app/src/cloud/campaign-service.ts';
import { createCheckModel } from '../development/cloud/model/check-client.mjs';
import { stringifyApplicationJson, parseApplicationJson } from '../onecrew_lite-contracts/src/json.ts';
import { campaignResults } from '../onecrew_lite-web/src/cloud/result-contracts.ts';
const directory = resolve('.scratch/basic-workflow-20261025'), campaign = 'cca38d34-30b3-49f9-8639-ef5d26d38e3a', origin = 'https://cloud.example.com';
const metadata = new DatabaseSync(join(directory, 'cloud.sqlite'), { readOnly: true });
const shops = metadata.prepare('SELECT shop FROM shopify_installations WHERE uninstalled_at IS NULL').all();
metadata.close();
assert.equal(shops.length, 1);
const shop = shops[0].shop;
async function open() {
  const resources = new AsyncDisposableStack();
  const storage = await openCloudStorage(directory);
  resources.defer(() => storage.close());
  const browsers = new ShopBrowserManager({ dataDirectory: directory, image: 'onecrew-cloud-browser:worker', seccompProfile: resolve('development/cloud/browser/seccomp-profile.json') }, storage.installations, storage.browserSnapshots);
  resources.defer(() => browsers.close());
  const tables = await openCloudLibrary(storage.lease, origin);
  resources.defer(() => tables.close());
  const runtimes = new ShopRuntimeRegistry();
  resources.defer(() => runtimes.close());
  const data = new ShopDataService(storage.lease, storage.installations, runtimes);
  const library = new ShopLibraryService(tables, data, origin);
  return { resources, storage, browsers, tables, runtimes, data, library };
}
const first = await open();
await using beforeResources = first.resources;
const before = campaignResults.parse(parseApplicationJson(stringifyApplicationJson({ ...await first.data.results(shop, campaign, null, null), library: await first.library.campaignResults(shop, campaign) })));
assert.ok(before.counts.qualified > 0);
const scored = before.library.creators.recommendations.filter(creator => creator.values.score);
assert.ok(scored.length > 0);
const service = new CloudCampaignService({ data: first.data, installations: first.storage.installations, jobs: first.storage.campaignJobs, templates: first.storage.campaignTemplates, browsers: first.browsers, library: first.library, model: createCheckModel(), reportFailure: () => assert.fail('回读不能启动任务'), onFatal: () => assert.fail('回读不应失败') });
const template = await service.saveTemplate(shop, { id: randomUUID(), name: 'FreeSip 本地验证条件', campaign_id: campaign, expected_revision: before.campaign.revision });
assert.deepEqual(template.conditions, { platforms: ['youtube'], min_followers: 10000, max_followers: 1000000, target_count: 10 });
await beforeResources.disposeAsync();
const second = await open();
await using afterResources = second.resources;
const after = campaignResults.parse(parseApplicationJson(stringifyApplicationJson({ ...await second.data.results(shop, campaign, null, null), library: await second.library.campaignResults(shop, campaign) })));
assert.deepEqual(after, before);
assert.equal(second.storage.campaignTemplates.get(shop, template.id).id, template.id);
console.info(stringifyApplicationJson({ event: 'cloud.basic_results_persisted', campaign, searchHits: after.hits.length, candidates: after.candidates.length, counts: after.counts, scoredRecommendations: scored.map(row => ({ name: row.values.name.name, url: row.values.name.url, score: row.values.score.level })), tableId: after.library.table.id, templateId: template.id, conditions: template.conditions, persistedAfterReopen: true, modelCalled: false, taskCompleted: false, shopifyNetworkVerified: false }));
