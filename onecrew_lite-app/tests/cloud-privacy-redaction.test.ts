import assert from "node:assert/strict";
import { createHash, randomBytes, randomUUID } from "node:crypto";
import { cp, lstat, mkdir, mkdtemp, rm } from "node:fs/promises";
import { join } from "node:path";
import { Readable, Writable } from "node:stream";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { Session } from "@shopify/shopify-api";
import { openCloudStorage } from "../src/cloud/storage.ts";
import { ShopRuntimeRegistry } from "../src/cloud/shop-runtime-registry.ts";
import { ShopDataService } from "../src/cloud/shop-data.ts";
import { openCloudLibrary, ShopLibraryService } from "../src/cloud/shop-library.ts";
import { ShopifyPrivacyService } from "../src/shopify/privacy-service.ts";
import { ShopifyUninstallProcessor } from "../src/shopify/uninstall-processor.ts";
import type { VerifiedWebhookEnvelope } from "../src/shopify/installation-store.ts";

test("privacy queue removes shop data and a cold backup restores the other store without restoring deleted data", { timeout: 30000 }, async () => {
  const scratch = fileURLToPath(new URL("../../.scratch/", import.meta.url));
  await mkdir(scratch, { recursive: true });
  const root = await mkdtemp(join(scratch, "privacy-redaction-")), directory = join(root, "private");
  const storage = await openCloudStorage(directory, true), runtimes = new ShopRuntimeRegistry();
  const tables = await openCloudLibrary(storage.lease, "https://cloud.example.com");
  const data = new ShopDataService(storage.lease, storage.installations, runtimes), library = new ShopLibraryService(tables, data, "https://cloud.example.com");
  const privacy = new ShopifyPrivacyService({ installations: storage.installations, data, library, jobs: storage.campaignJobs, templates: storage.campaignTemplates, snapshots: storage.browserSnapshots });
  const failures: unknown[] = [], processor = new ShopifyUninstallProcessor(storage.installations, runtimes, error => { failures.push(error); }, undefined, privacy);
  const first = "first.myshopify.com", second = "second.myshopify.com", jobId = randomUUID(), source = randomUUID(), templateId = randomUUID();
  const session = (shop: string) => new Session({ id: `offline_${shop}`, shop, state: "", isOnline: false, accessToken: randomBytes(32).toString("hex"), scope: "read_products" });
  const envelope = (shop: string, topic: VerifiedWebhookEnvelope["topic"], body: unknown): VerifiedWebhookEnvelope => ({ webhookId: randomUUID(), shop, topic, apiVersion: "2026-10", triggeredAt: null, body: JSON.stringify(body) });
  try {
    const owner = storage.installations.install(session(first), 0), other = storage.installations.install(session(second), 0);
    const firstData = await data.resolve(first), otherData = await data.resolve(second);
    const account = await firstData.databases.accountDirectory(firstData.runtime.context);
    const firstTenant = await tables.tenants.resolveShop(first), secondTenant = await tables.tenants.resolveShop(second);
    // 明确的手工业务记录与归档字节，不冒充搜索结果、模型输出或真实 Shopify 事件。
    const removed = await tables.service.createTable(firstTenant, { name: "本地隐私验收记录", columns: [{ name: "备注", data_type: "string" }] });
    const retained = await tables.service.createTable(secondTenant, { name: "另一个店铺的记录", columns: [{ name: "备注", data_type: "string" }] });
    const firstOwner = { shop: first, tenant_id: owner.tenant_id, base_id: owner.base_id };
    const snapshotKey = createHash("sha256").update(JSON.stringify([first, owner.tenant_id, owner.base_id])).digest("hex");
    const snapshot = await storage.browserSnapshots.save(firstOwner, Readable.from([Buffer.from("手工归档验收字节")]), new AbortController().signal);
    storage.installations.recordBrowserSnapshot(firstOwner, snapshot.id, 0);
    const otherOwner = { shop: second, tenant_id: other.tenant_id, base_id: other.base_id };
    const otherSnapshot = await storage.browserSnapshots.save(otherOwner, Readable.from([Buffer.from("保留店铺的备份验收标记")]), new AbortController().signal);
    storage.installations.recordBrowserSnapshot(otherOwner, otherSnapshot.id, 0);
    const reference = { id: source, brief: "寻找商品测评创作者", opencli_version: "1.8.8", target_count: 10, scopes: [{ platform: "youtube", profile_ref: "cloud", keywords: ["商品测评"] }], criteria: { min_subscribers: 10000, max_subscribers: 100000 } };
    const otherRepository = await otherData.databases.discoveryResolver().resolve(otherData.runtime.context);
    otherRepository.repository.create(reference);
    storage.campaignJobs.begin({ id: jobId, shop: first, campaign_id: source, kind: "draft", brief: "本地隐私验收", expected_revision: null, request: {}, product: null });
    storage.campaignJobs.finish(first, jobId, "failed", "failed", "local.manual_record");
    storage.campaignTemplates.save(first, { id: templateId, name: "本地验收", campaign_id: source, expected_revision: 1 }, reference);
    const request = envelope(first, "CUSTOMERS_DATA_REQUEST", { shop_id: 1, shop_domain: first, customer: { id: 1 }, data_request: { id: 1 }, orders_requested: [] });
    processor.receiveVerifiedWebhook(request);
    await processor.drain();
    assert.equal(storage.installations.privacyRequests(first).length, 1);
    const uninstall = envelope(first, "APP_UNINSTALLED", { local_storage_check: true });
    processor.receiveVerifiedWebhook(uninstall);
    await processor.drain();
    assert.equal(firstData.runtime.context.signal.aborted, true);
    const deletion = envelope(first, "SHOP_REDACT", { shop_id: 1, shop_domain: first });
    processor.receiveVerifiedWebhook(deletion);
    const repeatedDeletion = { ...deletion, webhookId: randomUUID() };
    processor.receiveVerifiedWebhook(repeatedDeletion);
    assert.throws(() => storage.installations.install(session(first), storage.installations.lifecycleRevision(first)), /uninstall_processing/u);
    await processor.drain();
    const revision = storage.installations.lifecycleRevision(first);
    assert.equal(storage.installations.workspace(first), null);
    assert.equal(storage.installations.session(first), null);
    assert.equal(storage.installations.browserSnapshot(first), null);
    assert.deepEqual(storage.campaignJobs.recent(first), []);
    assert.deepEqual(storage.campaignTemplates.list(first), []);
    assert.deepEqual(storage.installations.privacyRequests(first), []);
    assert.deepEqual(storage.installations.pendingWebhooks(), []);
    await assert.rejects(lstat(account.directory), { code: "ENOENT" });
    await assert.rejects(lstat(join(directory, "browser-snapshots", snapshotKey)), { code: "ENOENT" });
    await assert.rejects(tables.service.getTable(firstTenant, removed.id));
    assert.equal((await tables.service.getTable(secondTenant, retained.id)).name, "另一个店铺的记录");
    otherData.assertCurrent();
    assert.equal(storage.installations.workspace(second)?.tenant_id, other.tenant_id);
    processor.receiveVerifiedWebhook(deletion);
    await processor.drain();
    assert.equal(storage.installations.lifecycleRevision(first), revision);
    await processor.close(); await runtimes.close(); await tables.close(); await storage.close();
    const backup = join(root, "cold-backup"), restored = join(root, "restored");
    await cp(directory, backup, { recursive: true, force: false, errorOnExist: true, preserveTimestamps: true });
    await cp(backup, restored, { recursive: true, force: false, errorOnExist: true, preserveTimestamps: true });
    const reopened = await openCloudStorage(restored), restoredRuntimes = new ShopRuntimeRegistry();
    const restoredTables = await openCloudLibrary(reopened.lease, "https://cloud.example.com");
    try {
      assert.equal(reopened.installations.workspace(first), null);
      assert.equal(reopened.installations.lifecycleRevision(first), revision);
      assert.throws(() => reopened.installations.install(session(first), 0), /installation_changed/u);
      const fresh = reopened.installations.install(session(first), revision);
      assert.notEqual(fresh.tenant_id, owner.tenant_id);
      const replay = reopened.installations.receiveVerifiedWebhook(deletion);
      assert.notEqual(replay.completed_at, null);
      assert.equal(reopened.installations.workspace(first)?.uninstalled_at, null);
      assert.throws(() => reopened.installations.receiveVerifiedWebhook({ ...deletion, body: JSON.stringify({ shop_id: 2, shop_domain: first }) }), /webhook_conflict/u);
      assert.equal((await restoredTables.service.getTable(secondTenant, retained.id)).name, "另一个店铺的记录");
      await assert.rejects(restoredTables.service.getTable(firstTenant, removed.id));
      const restoredData = new ShopDataService(reopened.lease, reopened.installations, restoredRuntimes);
      assert.equal((await restoredData.campaign(second, source)).brief, reference.brief);
      const chunks: Buffer[] = [];
      await reopened.browserSnapshots.restoreTo(otherOwner, otherSnapshot.id, new Writable({ write(chunk, _encoding, done) { chunks.push(Buffer.from(chunk)); done(); } }), new AbortController().signal);
      assert.equal(Buffer.concat(chunks).toString(), "保留店铺的备份验收标记");
      console.info(JSON.stringify({ event: "cloud.cold_backup_restore_verified", sqliteRestored: true, libraryRestored: true, snapshotAuthenticated: true, redactedShopAbsent: true, replaySafeAfterReinstall: true }));
    } finally { await restoredRuntimes.close(); await restoredTables.close(); await reopened.close(); }
    assert.deepEqual(failures, []);
  } finally { await processor.close(); await runtimes.close(); await tables.close(); await storage.close(); await rm(root, { recursive: true }); }
});
