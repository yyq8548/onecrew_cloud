import assert from "node:assert/strict";
import { randomBytes } from "node:crypto";
import { chmod, copyFile, mkdir, mkdtemp, rm } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import test from "node:test";
import { Session } from "@shopify/shopify-api";
import { openCloudStorage } from "../src/cloud/storage.ts";
import { ShopRuntimeRegistry } from "../src/cloud/shop-runtime-registry.ts";
import { ShopDataService } from "../src/cloud/shop-data.ts";
import { openCloudLibrary, ShopLibraryService } from "../src/cloud/shop-library.ts";
import { parseApplicationJson, stringifyApplicationJson } from "../src/contracts/application-json.ts";
import { campaignResults, reviewMaterial } from "../../onecrew_lite-web/src/cloud/result-contracts.ts";

test("shared real PGlite keeps Shopify Library tenants separate and persistent without Access email", { timeout: 20000 }, async () => {
  const scratch = fileURLToPath(new URL("../../.scratch/", import.meta.url));
  await mkdir(scratch, { recursive: true });
  const root = await mkdtemp(join(scratch, "shop-library-"));
  const directory = join(root, "private"), origin = "https://cloud.example.com";
  const storage = await openCloudStorage(directory, true);
  const tables = await openCloudLibrary(storage.lease, origin);
  const runtimes = new ShopRuntimeRegistry();
  let firstId = "", secondId = "";
  try {
    const data = new ShopDataService(storage.lease, storage.installations, runtimes);
    const library = new ShopLibraryService(tables, data, origin);
    const first = "first.myshopify.com", second = "second.myshopify.com";
    for (const shop of [first, second]) storage.installations.install(new Session({ id: `offline_${shop}`, shop, state: "", isOnline: false, accessToken: randomBytes(32).toString("hex"), scope: "read_products" }), 0);
    const owner = await tables.tenants.resolveShop(first), other = await tables.tenants.resolveShop(second);
    assert.equal(owner.user.email, undefined);
    assert.equal(owner.user.id, `shopify:${first}`);
    assert.deepEqual(await tables.tenants.resolveShop(first), owner);
    assert.notEqual(owner.baseId, other.baseId);
    assert.notEqual(owner.tenantId, other.tenantId);
    assert.throws(() => tables.tenants.resolve({ id: owner.user.id, email: "invented@example.com" }));
    assert.throws(() => tables.tenants.resolveShop("first.myshopify.com.attacker.test"));
    firstId = (await tables.service.createTable(owner, { name: "护肤商品合作", columns: [{ name: "备注", data_type: "string" }] })).id;
    secondId = (await tables.service.createTable(other, { name: "鞋类商品合作", columns: [{ name: "备注", data_type: "string" }] })).id;
    assert.deepEqual((await library.list(first, 1, 25)).tables.map(table => table.id), [firstId]);
    assert.deepEqual((await library.list(second, 1, 25)).tables.map(table => table.id), [secondId]);
    await assert.rejects(library.table(second, firstId), { status: 404 });
    const firstData = await data.resolve(first);
    await library.projection(firstData).readiness(firstData.runtime.context);
    const account = await firstData.databases.accountDirectory(firstData.runtime.context);
    await runtimes.remove(first);
    await copyFile(fileURLToPath(new URL("./fixtures/discovery-identity/merged.sqlite", import.meta.url)), join(account.directory, "creator.sqlite"));
    await chmod(join(account.directory, "creator.sqlite"), 0o600);
    const publicationData = await data.resolve(first);
    const owned = await publicationData.databases.discoveryResolver().resolve(publicationData.runtime.context);
    const campaign = owned.repository.getPlan(owned.repository.recentPlans()[0]!.id);
    const projection = library.projection(publicationData);
    const published = await projection.publish(publicationData.runtime.context, campaign.id, campaign.revision);
    assert.ok(published.total_hits > 0);
    assert.equal(published.inserted_rows, published.total_hits);
    const replayed = await projection.publish(publicationData.runtime.context, campaign.id, campaign.revision);
    assert.equal(replayed.table_id, published.table_id);
    assert.equal(replayed.inserted_rows, 0);
    const creators = await library.creators(first, published.table_id);
    assert.equal(creators.state, "current");
    assert.ok(creators.recommendations.length > 0);
    const results = await data.results(first, campaign.id, null, null);
    const savedLibrary = await library.campaignResults(first, campaign.id);
    const decoded = campaignResults.parse(parseApplicationJson(stringifyApplicationJson({ ...results, library: savedLibrary })));
    assert.equal(decoded.library.table?.id, published.table_id);
    assert.equal(decoded.library.creators?.state, "current");
    assert.equal(decoded.library.creators?.recommendations[0]?.id, creators.recommendations[0]?.id);
    assert.ok(decoded.hits.length > 0);
    assert.ok(decoded.candidates.length > 0);
    const source = creators.sources.find(source => source.verdict === "qualified");
    assert.ok(source);
    const material = await data.reviewMaterial(first, campaign.id, source.search_hit_id, campaign.revision);
    const decodedMaterial = reviewMaterial.parse(parseApplicationJson(stringifyApplicationJson({ material }))).material;
    assert.equal(decodedMaterial.campaign_id, campaign.id);
    assert.equal(decodedMaterial.hit.id, source.search_hit_id);
    assert.ok(decodedMaterial.material_hash);
    await assert.rejects(data.results(second, campaign.id, null, null), /plan_missing/u);
    await assert.rejects(data.reviewMaterial(second, campaign.id, source.search_hit_id, campaign.revision), /plan_missing/u);
    await assert.rejects(data.reviewMaterial(first, campaign.id, source.search_hit_id, campaign.revision + 1), /revision_changed/u);
    await assert.rejects(data.reviewMaterial(first, campaign.id, "absent", campaign.revision), /review_material_unavailable/u);
    const afterLast = await data.results(first, campaign.id, results.hits.at(-1)!.id, results.candidates.at(-1)!.id);
    assert.deepEqual(afterLast.hits, []);
    assert.deepEqual(afterLast.candidates, []);
    await assert.rejects(library.creators(second, published.table_id), { status: 404 });
    storage.installations.uninstall(first);
    await runtimes.remove(first);
    await assert.rejects(library.table(first, firstId), /installation_required/u);
    assert.equal((await library.table(second, secondId)).id, secondId);
  } finally { await runtimes.close(); await tables.close(); await storage.close(); }
  const reopened = await openCloudStorage(directory);
  const restoredTables = await openCloudLibrary(reopened.lease, origin);
  const restoredRuntimes = new ShopRuntimeRegistry();
  try {
    const library = new ShopLibraryService(restoredTables, new ShopDataService(reopened.lease, reopened.installations, restoredRuntimes), origin);
    assert.equal((await library.table("second.myshopify.com", secondId)).name, "鞋类商品合作");
    await assert.rejects(library.table("second.myshopify.com", firstId), { status: 404 });
  } finally { await restoredRuntimes.close(); await restoredTables.close(); await reopened.close(); await rm(root, { recursive: true }); }
});
